/** The "Why did this happen?" side-panel copy for an event. */
export function explanationForEvent(e: GameEvent): string | null {
  if (e.explanation) {
    const x = e.explanation;
    return `Что: ${x.what}\nПочему: ${x.why}\nФакторы: ${x.factors.join(', ')}\nЦена вопроса: $${x.costUsd}\nРиск: ${x.riskNote}\nИначе: ${x.alternative}`;
  }
  return null;
}

